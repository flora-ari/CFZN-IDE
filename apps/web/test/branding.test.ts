test('the supplied PNG stays byte-identical and its display viewport includes the complete visible wordmark and Chinese subtitle', () => {
  const png = readFileSync(new URL('../public/branding/ccraft-logo.png', import.meta.url));
  assert.equal(createHash('sha256').update(png).digest('hex'), 'c927127553d58dcfdb4de6487da3a2c894266d6a78b9de05d3e9535da2d010c2');
  const width = png.readUInt32BE(16), height = png.readUInt32BE(20);
  assert.deepEqual([width, height, png[24], png[25], png[28]], [1448, 1086, 8, 6, 0]);
  const chunks = [];
  for (let offset = 8; offset < png.length;) {
    const length = png.readUInt32BE(offset);
    if (png.toString('ascii', offset + 4, offset + 8) === 'IDAT') chunks.push(png.subarray(offset + 8, offset + 8 + length));
    offset += 12 + length;
  }
  // Read-only reconstruction of PNG scanlines; no image file is transformed or written.
  const raw = inflateSync(Buffer.concat(chunks)), stride = width * 4, pixels = Buffer.alloc(stride * height);
  const paeth = (a: number, b: number, c: number) => { const p = a + b - c, pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c); return pa <= pb && pa <= pc ? a : pb <= pc ? b : c; };
  let left = width, top = height, right = -1, bottom = -1;
  for (let y = 0; y < height; y++) {
    const filter = raw[y * (stride + 1)]; assert.ok(filter >= 0 && filter <= 4);
    for (let x = 0; x < stride; x++) {
      const a = x >= 4 ? pixels[y * stride + x - 4] : 0, b = y ? pixels[(y - 1) * stride + x] : 0, c = y && x >= 4 ? pixels[(y - 1) * stride + x - 4] : 0;
      pixels[y * stride + x] = (raw[y * (stride + 1) + 1 + x] + (filter === 0 ? 0 : filter === 1 ? a : filter === 2 ? b : filter === 3 ? Math.floor((a + b) / 2) : paeth(a, b, c))) & 255;
      if (x % 4 === 3 && pixels[y * stride + x] > 16) { const pixelX = (x - 3) / 4; left = Math.min(left, pixelX); top = Math.min(top, y); right = Math.max(right, pixelX); bottom = Math.max(bottom, y); }
    }
  }
  assert.deepEqual([left, top, right, bottom], [101, 347, 1353, 770]);
  const css = readFileSync(new URL('../src/native-project-toolbar.css', import.meta.url), 'utf8');
  const rule = css.match(/\[data-cfzn-menu-host\] img\[data-cfzn-brand-logo\][^{]+\{([^}]+)\}/)![1];
  assert.match(rule, /object-fit: cover/); assert.match(rule, /opacity: 1/);
  const boxWidth = Number(rule.match(/(?:^|;)\s*width: (\d+)px/)![1]), boxHeight = Number(rule.match(/(?:^|;)\s*height: (\d+)px/)![1]);
  const position = rule.match(/object-position: (\d+)% (\d+)%/)!.slice(1).map(Number);
  const scale = Math.max(boxWidth / width, boxHeight / height);
  const viewportLeft = (width * scale - boxWidth) * position[0] / 100 / scale;
  const viewportTop = (height * scale - boxHeight) * position[1] / 100 / scale;
  assert.ok(left >= viewportLeft && right + 1 <= viewportLeft + boxWidth / scale);
  assert.ok(top >= viewportTop && bottom + 1 <= viewportTop + boxHeight / scale);
});
