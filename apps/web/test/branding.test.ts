test('generator branding changes only the exact first line and the real mode adapter preserves manual drafts', async () => {
  const body = 'const char *message = "Hello OpenBlock";\n// OpenBlock is user commentary\n';
  for (const ending of ['\n', '\r\n', '\r', '']) {
    const code = '// generated by OpenBlock' + ending + (ending ? body : '');
    assert.equal(brandGeneratedSource(code), '// generated by CCraft' + ending + (ending ? body : ''));
  }
  for (const code of [body, '\n// generated by OpenBlock\n', '// generated by OpenBlock user note\n', '# generated by OpenBlock\n']) assert.equal(brandGeneratedSource(code), code);
  const code = { isCodeEditorLocked: true, codeEditorValue: '' };
  const store = { getState: () => ({ scratchGui: { code } }), dispatch: (action: any) => {
    if (action.type.endsWith('/TOGGLE_LOCK')) code.isCodeEditorLocked = !code.isCodeEditorLocked;
    if (action.type.endsWith('/UPDATE_CODE')) code.codeEditorValue = action.value;
  } };
  const modes = new ModeController({}, () => store, () => '', () => {});
  const generated = '// generated by OpenBlock\n' + body;
  modes.generate({ Arduino: { workspaceToCode: () => generated } }, {});
  assert.equal(modes.generatedSource, '// generated by CCraft\n' + body);
  assert.equal(code.codeEditorValue, modes.generatedSource);
  modes.chooseCode('manual'); assert.equal(modes.manualSource, modes.generatedSource);
  modes.editManual(generated);
  modes.generate({ Arduino: { workspaceToCode: () => generated + '// another generated line\n' } }, {});
  assert.equal(modes.selectedSource, generated); assert.equal(code.codeEditorValue, generated);
  await modes.restore({ version: 1, codeMode: 'manual', manualSource: generated });
  assert.equal(modes.metadata().manualSource, generated);
});

