test('audited GUI messages cover every shipped locale, preserve interpolation and leave unrelated content untouched', () => {
  for (const [locale, source] of Object.entries(messages) as [string, Record<string, string>][]) {
    const before = JSON.stringify(source), branded = brandMessages(source, locale);
    for (const id of brandIds) {
      assert.doesNotMatch(branded[id], /openblock/i, `${locale}: ${id}`);
      assert.equal(typeof branded[id], 'string');
    }
    for (const id of ['gui.alerts.lostPeripheralConnection', 'gui.webglModal.description']) {
      assert.deepEqual(branded[id].match(/\{[^}]+\}/g), source[id].match(/\{[^}]+\}/g));
    }
    assert.doesNotMatch(branded['gui.connection.unavailable.installscratchlink'], /CCraft\s*Link/);
    assert.doesNotMatch(branded['gui.crashMessage.description'], /automatically reported|自动报告|自動回報|автоматически/i);
    for (const id of Object.keys(source).filter(id => !brandIds.includes(id) && id !== 'gui.menuBar.wiki')) assert.equal(branded[id], source[id], id);
    assert.equal(JSON.stringify(source), before);
  }
  const source = { 'unrelated.userLabel': 'Hello OpenBlock', [DEFAULT_PROJECT_TITLE]: '' };
  const branded = brandMessages(source, 'en');
  assert.equal(branded['unrelated.userLabel'], 'Hello OpenBlock');
  assert.equal(branded[DEFAULT_PROJECT_TITLE], 'CCraft Project');
});

